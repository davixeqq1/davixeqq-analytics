// ---------- formatting (mirrors yt_report/formatting.py: round half away from zero) ----------
const NA = "n/a";
// toPrecision(15) strips binary noise (1.005 * 100 = 100.49999… -> 100.5) before rounding.
const rh = (v, d = 0) => {
  const f = 10 ** d, r = Math.round(Number((Math.abs(v) * f).toPrecision(15))) / f;
  return r === 0 ? 0 : Math.sign(v) * r;
};
const fixed = (v, d) => rh(v, d).toFixed(d);
const nf = new Intl.NumberFormat("en-US");
const fmtInt = (v) => (v == null ? NA : nf.format(rh(v)));
const fmtHours = (min) => {
  if (min == null) return NA;
  const h = min / 60, d = Math.abs(h) >= 10 ? 1 : 2;
  return `${rh(h, d).toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d })} h`;
};
const fmtPct = (v) => (v == null ? NA : `${fixed(v, 1)}%`);
const fmtDur = (s) => {
  if (s == null) return NA;
  s = rh(s); const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = s % 60;
  return h ? `${h}:${String(m).padStart(2, "0")}:${String(sec).padStart(2, "0")}` : `${m}:${String(sec).padStart(2, "0")}`;
};
const fmtSigned = (v) => (v == null ? NA : (v > 0 ? "+" : "") + nf.format(rh(v)));
const fmtChange = (ch, d = 1) => (ch == null ? NA : `${rh(ch, d) > 0 ? "+" : ""}${fixed(ch, d)}%`);
const fmtDate = (iso) => new Date(iso + "T00:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric" });
const periodLabel = (a, b) => `${fmtDate(a)} – ${fmtDate(b)}, ${b.slice(0, 4)}`;
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const pctChange = (cur, prev) => (cur == null || prev == null || prev === 0 ? null : ((cur - prev) / Math.abs(prev)) * 100);
const net = (t) => (t && t.subs_gained != null && t.subs_lost != null ? t.subs_gained - t.subs_lost : null);
const safeUrl = (u) => (typeof u === "string" && /^https:\/\//.test(u) ? u : "#");
// Images: https, or the inline SVG placeholders generated by demo mode.
const safeImg = (u) => (typeof u === "string" && (/^https:\/\//.test(u) || /^data:image\/svg\+xml;base64,[A-Za-z0-9+/=]+$/.test(u)) ? u : null);
const $ = (id) => document.getElementById(id);

